# Heatmap cell annotations were 12pt; bumped to 16pt. Related axis/title sizes +4 for consistency.
HEATMAP_ANNOT_FONT = 16
HEATMAP_AXIS_LABEL_FONT = 16
HEATMAP_TICK_LABEL_FONT = 16
HEATMAP_TITLE_FONT = 18

# Full cell-type names (h5ad / data_preparation.py) -> short labels for figure axes only.
CELL_TYPE_TO_ABBREV = {
    "Others": "Oth",
    "Tumor": "Tum",
    "Lymphocyte": "Lym",
    "Fibroblast/Stroma": "Fib/Str",
}

# Left-to-right column order on composition heatmaps (full names as in adata / CSV).
CELL_TYPE_HEATMAP_ORDER_FULL: Tuple[str, ...] = (
    "Others",
    "Tumor",
    "Lymphocyte",
    "Fibroblast/Stroma",
)


def _canonical_cell_type_column_order(columns) -> List[str]:
    """Stable order: canonical list first, then any other columns in their original order."""
    col_list = list(columns)
    seen: set = set()
    unique_cols: List[str] = []
    for c in col_list:
        s = str(c)
        if s not in seen:
            seen.add(s)
            unique_cols.append(s)
    canon_set = set(CELL_TYPE_HEATMAP_ORDER_FULL)
    ordered = [c for c in CELL_TYPE_HEATMAP_ORDER_FULL if c in seen]
    remaining = [c for c in unique_cols if c not in canon_set]
    return ordered + remaining


def _reorder_cell_type_columns_canonical(df: pd.DataFrame) -> pd.DataFrame:
    """Reorder columns for heatmaps; indices unchanged."""
    order = _canonical_cell_type_column_order(df.columns)
    return df.loc[:, order].copy()


def _rename_cell_type_columns_for_plot(df: pd.DataFrame) -> pd.DataFrame:
    """Copy of df with column names abbreviated for heatmaps only (CSVs unchanged)."""
    out = df.copy()
    out.columns = [CELL_TYPE_TO_ABBREV.get(str(c), str(c)) for c in out.columns]
    return out


def _prepare_composition_df_for_heatmap(df: pd.DataFrame) -> pd.DataFrame:
    """Canonical cell-type order, then abbreviations, for composition heatmaps only."""
    return _rename_cell_type_columns_for_plot(_reorder_cell_type_columns_canonical(df))


def _resolve_n_clusters_from_adata(
    adata: ad.AnnData,
    cn_key: str,
    n_clusters: Optional[int] = None,
) -> int:
    """Return the number of CNs present in data (authoritative for plot titles).

    If an explicit n_clusters is passed and disagrees with the data, warn and
    use the data count so titles match the figure.
    """
    n_from_data = int(adata.obs[cn_key].nunique())
    if n_clusters is not None and int(n_clusters) != n_from_data:
        print(
            f"  Warning: n_clusters={n_clusters} was requested, but data has "
            f"{n_from_data} unique CN labels in '{cn_key}'; "
            f"using {n_from_data} for titles."
        )
    return n_from_data


def load_tile_selection(csv_path) -> Set[str]:
    """
    Load a set of tile names to include, from a CSV with a 'tile' column
    (e.g. one row per tile: 'JN_TS_001_tile_12883_7423'). Tile names should
    match each h5ad file's stem (filename without the .h5ad extension).

    Used to restrict analysis to a subset of tiles — e.g. excluding tiles for
    QC reasons, or spot-checking a subset — without needing to move/delete
    the underlying h5ad or CN-label files.
    """
    df = pd.read_csv(csv_path)
    if 'tile' not in df.columns:
        raise ValueError(
            f"Expected a 'tile' column in {csv_path}, found columns: {list(df.columns)}"
        )
    tiles = set(df['tile'].astype(str).str.strip())
    print(f"✓ Loaded tile selection: {len(tiles)} tiles from {csv_path}")
    return tiles


def _infer_n_clusters_from_path(path: Path) -> Optional[int]:
    """Infer n_clusters from path segments like all_n_cluster=4 or results_n=4."""
    import re
    for part in [path.name, path.parent.name, *path.parts[::-1]]:
        match = re.search(r'n_clusters?[=_]?(\d+)', part)
        if match:
            return int(match.group(1))
        match = re.search(r'(?:^|[_-])n[=_](\d+)', part)
        if match:
            return int(match.group(1))
    return None


def _is_integer_cn_labels(labels) -> bool:
    """Check if CN labels are integers (1, 2, 3) vs strings (CN1, CN3-1)."""
    for x in labels:
        try:
            int(float(str(x).strip()))
        except (ValueError, TypeError):
            return False
    return True


def _sort_cn_labels_and_colors(labels, color_palette: str = 'tab20'):
    """
    Sort CN labels and return (sorted_labels, colors).
    Supports both integer labels (1, 2, 3) and string labels (CN1, CN2, CN3-1).
    """
    labels = list(labels)
    if not labels:
        return [], []

    if _is_integer_cn_labels(labels):
        int_labels = [int(float(str(x).strip())) for x in labels]
        sorted_labels = sorted(set(int_labels), key=lambda x: x)
        palette = sns.color_palette(color_palette, max(sorted_labels))
        colors = [palette[x - 1] for x in sorted_labels]
        return sorted_labels, colors
    else:
        def sort_key(s):
            s = str(s).strip()
            if not s.startswith('CN'):
                return (999, 0)
            rest = s[2:]
            if '-' in rest:
                parts = rest.split('-', 1)
                return (int(parts[0]) if parts[0].isdigit() else 999,
                        int(parts[1]) if parts[1].isdigit() else 0)
            return (int(rest) if rest.isdigit() else 999, 0)

        sorted_labels = sorted(set(labels), key=sort_key)
        n = len(sorted_labels)
        palette = sns.color_palette(color_palette, max(n, 20))[:n]
        colors = list(palette)
        return sorted_labels, colors


class GroupCNAnalyzer:
    """Analyzes cellular neighborhoods by predefined groups."""

    def __init__(
        self,
        source_h5ad_dir: str,
        cn_labels_dir: str,
        categories_json: str,
        output_dir: str,
        tile_selection: Optional[Set[str]] = None,
    ):
        """
        Initialize group CN analyzer.

        Parameters:
        -----------
        source_h5ad_dir : str
            Directory containing the ORIGINAL h5ad tiles produced by
            data_preparation.py (already have cell_type + spatial; not
            modified by clustering). Named "{tile_name}.h5ad".
        cn_labels_dir : str
            Directory containing the lightweight per-tile CN-label JSON files
            written by cn_unified_kmeans_local.py's save_cn_labels() (its
            output_dir/cn_labels/ folder). Named "{tile_name}_cn_labels.json".
        categories_json : str
            Path to JSON file mapping group name -> list of tile IDs
            (plus an optional 'metadata' key with e.g. tile_size_mm2)
        output_dir : str
            Base output directory for all results
        tile_selection : set of str, optional
            If given, restrict analysis to only these tile names (see
            load_tile_selection). Tiles not in this set are excluded even if
            present in both source_h5ad_dir and cn_labels_dir.
        """
        self.source_h5ad_dir = Path(source_h5ad_dir)
        self.cn_labels_dir = Path(cn_labels_dir)
        self.categories_json = Path(categories_json)
        self.tile_selection = tile_selection
        base_output_dir = Path(output_dir)

        with open(self.categories_json, 'r') as f:
            self.categories = json.load(f)

        self.base_output_dir = base_output_dir
        self.base_output_dir.mkdir(parents=True, exist_ok=True)
        (self.base_output_dir / 'unified_analysis').mkdir(exist_ok=True)

        # Extract tile size from metadata and create subfolder for group analysis
        tile_size_mm = self.categories.get('metadata', {}).get('tile_size_mm2', 2.0)
        tile_size_folder = f"{int(tile_size_mm)}mm_groups"
        self.output_dir = base_output_dir / tile_size_folder
        self.output_dir.mkdir(parents=True, exist_ok=True)

        # Cache of the combined, all-tiles AnnData (populated by load_all_processed_tiles,
        # reused across unified analysis, each group's subset, and the combined
        # per-tile frequency figure — avoids re-reading/re-merging tiles repeatedly)
        self._combined_adata_cache: Optional[ad.AnnData] = None

        print(f"✓ Loaded tile categories from: {self.categories_json}")
        print(f"  Groups: {list(self.categories.keys() - {'metadata'})}")
        print(f"  Source h5ad directory: {self.source_h5ad_dir}")
        print(f"  CN labels directory: {self.cn_labels_dir}")
        if self.tile_selection is not None:
            print(f"  Tile selection: {len(self.tile_selection)} tiles")
        print(f"  Base output directory: {self.base_output_dir}")
        print(f"  Group analysis output: {self.output_dir}")

    def load_all_processed_tiles(
        self,
        cn_key: str = 'cn_celltype',
        celltype_key: str = 'cell_type',
        use_cache: bool = True
    ) -> ad.AnnData:
        """
        Load each tile's original source h5ad (cell_type + spatial, untouched
        by clustering) and merge in its CN labels from the matching lightweight
        JSON file, combining all tiles into a single AnnData object. Nothing
        new is written to disk here — the merge happens in memory.

        Cells with no matching CN label (e.g. a tile that wasn't part of the
        clustering run, or an individual cell dropped somewhere upstream) are
        excluded from the combined dataset, with a warning.

        Cached after the first call (use_cache=True) so repeated calls within
        the same run don't redo this merge for every tile again.
        """
        if use_cache and self._combined_adata_cache is not None:
            return self._combined_adata_cache

        print(f"\nLoading source h5ad tiles from: {self.source_h5ad_dir}")
        print(f"Merging in CN labels from: {self.cn_labels_dir}")

        h5ad_files = sorted(self.source_h5ad_dir.glob('*.h5ad'))
        if not h5ad_files:
            raise ValueError(f"No h5ad files found in {self.source_h5ad_dir}")
        print(f"Found {len(h5ad_files)} source h5ad files")

        if self.tile_selection is not None:
            found_stems = {f.stem for f in h5ad_files}
            missing = self.tile_selection - found_stems
            if missing:
                sample = sorted(missing)[:5]
                print(f"  Warning: {len(missing)} tile(s) from the selection list were not "
                      f"found in {self.source_h5ad_dir}: {sample}"
                      f"{' ...' if len(missing) > 5 else ''}")
            h5ad_files = [f for f in h5ad_files if f.stem in self.tile_selection]
            print(f"  Tile selection applied: keeping {len(h5ad_files)} tiles")
            if not h5ad_files:
                raise ValueError("No tiles remain after applying tile_selection")

        # Map tile_name -> cn_labels json path
        cn_label_files = sorted(self.cn_labels_dir.glob('*_cn_labels.json'))
        cn_label_map = {}
        suffix = '_cn_labels'
        for f in cn_label_files:
            stem = f.stem
            if stem.endswith(suffix):
                tile_name = stem[:-len(suffix)]
                cn_label_map[tile_name] = f
        if not cn_label_map:
            raise ValueError(f"No *_cn_labels.json files found in {self.cn_labels_dir}")
        print(f"Found {len(cn_label_map)} CN-label JSON files")

        adata_list = []
        cell_type_categories = None
        n_tiles_no_labels = 0

        for i, h5ad_file in enumerate(h5ad_files, 1):
            tile_name = h5ad_file.stem
            print(f"  [{i}/{len(h5ad_files)}] Loading {tile_name}...")

            if tile_name not in cn_label_map:
                print(f"    Warning: no CN-label JSON found for {tile_name}, skipping "
                      f"(this tile wasn't part of the clustering run, or naming doesn't match)")
                n_tiles_no_labels += 1
                continue

            try:
                adata = ad.read_h5ad(h5ad_file)

                if celltype_key not in adata.obs.columns:
                    print(f"    Warning: {celltype_key} not found, skipping")
                    continue

                if 'tile_name' not in adata.obs.columns:
                    adata.obs['tile_name'] = tile_name

                # Merge in CN labels from the lightweight JSON, matching by the
                # original nucleus ID (obs_name with the "{tile_name}_" prefix
                # stripped off — this is exactly how save_cn_labels() built the keys).
                with open(cn_label_map[tile_name], 'r') as f:
                    payload = json.load(f)
                labels = payload.get('labels', {})

                prefix = f"{tile_name}_"
                cn_values = []
                matched_mask = []
                for obs_name in adata.obs_names:
                    nucleus_id = str(obs_name)[len(prefix):] if str(obs_name).startswith(prefix) else str(obs_name)
                    if nucleus_id in labels:
                        cn_values.append(labels[nucleus_id])
                        matched_mask.append(True)
                    else:
                        cn_values.append(None)
                        matched_mask.append(False)

                matched_mask = np.array(matched_mask)
                n_unmatched = (~matched_mask).sum()
                if n_unmatched:
                    print(f"    Warning: {n_unmatched}/{adata.n_obs} cells in {tile_name} had "
                          f"no matching CN label; excluding them from analysis")

                if not matched_mask.any():
                    print(f"    Warning: no cells in {tile_name} matched a CN label, skipping tile")
                    continue

                adata = adata[matched_mask].copy()
                adata.obs[cn_key] = pd.Categorical(
                    [cn_values[j] for j in range(len(cn_values)) if matched_mask[j]]
                )

                if isinstance(adata.obs[celltype_key].dtype, pd.CategoricalDtype):
                    if cell_type_categories is None:
                        cell_type_categories = adata.obs[celltype_key].cat.categories.tolist()
                        print(f"    ✓ Preserving cell type order from first tile: {cell_type_categories}")
                    else:
                        # NOTE: deliberately NOT passing ordered=True here. If this tile's
                        # categorical ends up with a different 'ordered' flag than the first
                        # tile's, ad.concat treats the dtypes as incompatible and silently
                        # falls back to plain object dtype for the whole column across all
                        # tiles — silently breaking every downstream "preserve category
                        # order" step (composition columns then default to alphabetical).
                        adata.obs[celltype_key] = adata.obs[celltype_key].astype('category')
                        adata.obs[celltype_key] = adata.obs[celltype_key].cat.set_categories(
                            cell_type_categories
                        )
                elif cell_type_categories is None:
                    adata.obs[celltype_key] = pd.Categorical(adata.obs[celltype_key])
                    cell_type_categories = adata.obs[celltype_key].cat.categories.tolist()
                    print(f"    ✓ Cell types converted to categorical, order: {cell_type_categories}")

                adata_list.append(adata)
                print(f"    ✓ Loaded {adata.n_obs} cells (with matched CN labels)")

            except Exception as e:
                print(f"    ✗ Error loading {h5ad_file}: {str(e)}")
                continue

        if n_tiles_no_labels:
            print(f"\n  Note: {n_tiles_no_labels} source tile(s) had no matching CN-label file "
                  f"and were skipped entirely.")

        if not adata_list:
            raise ValueError("No valid tiles could be loaded and matched with CN labels")

        print(f"\nCombining {len(adata_list)} tiles...")
        combined_adata = ad.concat(adata_list, join='outer')

        if cell_type_categories is not None:
            if isinstance(combined_adata.obs[celltype_key].dtype, pd.CategoricalDtype):
                combined_adata.obs[celltype_key] = combined_adata.obs[celltype_key].cat.set_categories(
                    cell_type_categories
                )
            else:
                # ad.concat fell back to object dtype (e.g. because per-tile categoricals
                # weren't perfectly aligned) — explicitly restore categorical + order here
                # rather than silently losing it for every downstream step.
                combined_adata.obs[celltype_key] = pd.Categorical(
                    combined_adata.obs[celltype_key], categories=cell_type_categories
                )
                print(f"    ✓ Restored categorical dtype/order on combined data "
                      f"(concat had reverted it to {combined_adata.obs[celltype_key].dtype})")

        print(f"✓ Combined dataset: {combined_adata.n_obs:,} cells")
        print(f"  Tiles: {combined_adata.obs['tile_name'].nunique()}")
        print(f"  Cell types: {combined_adata.obs[celltype_key].nunique()}")

        if use_cache:
            self._combined_adata_cache = combined_adata

        return combined_adata

    def get_group_subset(self, combined_adata: ad.AnnData, group_name: str) -> ad.AnnData:
        """
        Subset the already-loaded combined AnnData to just the tiles belonging
        to group_name, instead of re-reading each tile's h5ad file from disk.
        """
        if group_name not in self.categories:
            raise ValueError(f"Group '{group_name}' not found in categories")

        tile_names = set(self.categories[group_name])
        mask = combined_adata.obs['tile_name'].isin(tile_names)
        subset = combined_adata[mask].copy()

        found_tiles = subset.obs['tile_name'].unique().tolist()
        missing = tile_names - set(found_tiles)
        if missing:
            print(f"  Warning: {len(missing)} tiles for group '{group_name}' not found "
                  f"in loaded data: {sorted(missing)[:5]}{'...' if len(missing) > 5 else ''}")

        if subset.n_obs == 0:
            raise ValueError(f"No cells found for group: {group_name}")

        print(f"✓ Group '{group_name}': {len(found_tiles)} tiles, {subset.n_obs:,} cells")
        return subset

    def compute_cn_composition(
        self,
        adata: ad.AnnData,
        cn_key: str = 'cn_celltype',
        celltype_key: str = 'cell_type'
    ) -> Tuple[pd.DataFrame, pd.DataFrame]:
        """Compute cell phenotype fractions in each CN for the given adata
        (works for the full combined dataset or any group subset)."""
        composition = pd.crosstab(
            adata.obs[cn_key],
            adata.obs[celltype_key],
            normalize='index'
        )

        if isinstance(adata.obs[celltype_key].dtype, pd.CategoricalDtype):
            cell_type_order = adata.obs[celltype_key].cat.categories.tolist()
            existing_cols = [col for col in cell_type_order if col in composition.columns]
            remaining_cols = [col for col in composition.columns if col not in existing_cols]
            composition = composition[existing_cols + remaining_cols]

        composition_zscore = composition.apply(lambda x: (x - x.mean()) / x.std(), axis=0)
        return composition, composition_zscore

    def calculate_neighborhood_frequency(
        self,
        adata: ad.AnnData,
        cn_key: str = 'cn_celltype',
        group_by_tile: bool = False
    ) -> pd.DataFrame:
        """
        Calculate the frequency of each cellular neighborhood for the given adata
        (works for the full combined dataset or any group subset).
        """
        print(f"\nCalculating neighborhood frequency...")

        if group_by_tile:
            frequency_df = pd.crosstab(
                adata.obs['tile_name'],
                adata.obs[cn_key],
                normalize='index'
            )
            print(f"  ✓ Calculated CN frequency per tile")
        else:
            cn_counts = adata.obs[cn_key].value_counts().sort_index()
            total_cells = len(adata.obs)
            cn_percentages = (cn_counts / total_cells * 100).round(2)

            frequency_df = pd.DataFrame({
                'Count': cn_counts,
                'Percentage': cn_percentages
            })
            frequency_df.index.name = 'Cellular_Neighborhood'
            frequency_df = frequency_df.reset_index()
            print(f"  ✓ Calculated overall CN frequency")
            print(f"    Total cells: {total_cells:,}")

        return frequency_df

    def visualize_unified_cn_composition(
        self,
        adata: ad.AnnData,
        composition_zscore: pd.DataFrame,
        k: int,
        n_clusters: int,
        figsize: Tuple[int, int] = (12, 8),
        cmap: str = 'coolwarm',
        vmin: float = -2,
        vmax: float = 2,
        save_path: Optional[str] = None,
        show_values: bool = True
    ):
        """Visualize unified CN composition as heatmap across ALL tiles.

        Column order follows CELL_TYPE_HEATMAP_ORDER_FULL (then abbreviations), not
        adata categorical order (which is often alphabetical after multi-tile concat).
        """
        print("\nVisualizing unified CN composition heatmap...")

        fig, ax = plt.subplots(figsize=figsize)

        z_plot = _prepare_composition_df_for_heatmap(composition_zscore)
        sns.heatmap(
            z_plot,
            cmap=cmap,
            center=0,
            vmin=vmin,
            vmax=vmax,
            cbar_kws={'label': 'Z-score'},
            linewidths=0.5,
            linecolor='white',
            ax=ax,
            annot=show_values,
            fmt='.2f' if show_values else '',
            annot_kws={'size': HEATMAP_ANNOT_FONT}
        )

        ax.set_xlabel('Cell Type', fontsize=HEATMAP_AXIS_LABEL_FONT, fontweight='bold')
        ax.set_ylabel('Cellular Neighborhood', fontsize=HEATMAP_AXIS_LABEL_FONT, fontweight='bold')

        n_tiles = adata.obs['tile_name'].nunique()
        n_cells = adata.n_obs
        title = (f'Unified Cell Type Composition by Cellular Neighborhood\n'
                f'(k={k}, n_clusters={n_clusters}, {n_tiles} tiles, {n_cells:,} cells)\n'
                f'Z-score scaled by column')
        ax.set_title(title, fontsize=HEATMAP_TITLE_FONT, fontweight='bold', pad=20)

        plt.setp(ax.get_xticklabels(), rotation=45, ha='right', fontsize=HEATMAP_TICK_LABEL_FONT)
        plt.setp(ax.get_yticklabels(), rotation=0, fontsize=HEATMAP_TICK_LABEL_FONT)

        plt.tight_layout()

        if save_path:
            plt.savefig(save_path, dpi=300, bbox_inches='tight')
            print(f"  ✓ Saved unified heatmap to: {save_path}")

        plt.close(fig)
        return fig

    def visualize_unified_neighborhood_frequency(
        self,
        adata: ad.AnnData,
        cn_key: str = 'cn_celltype',
        group_by_tile: bool = False,
        figsize: Tuple[int, int] = (12, 6),
        save_path: Optional[str] = None,
        color_palette: str = 'tab20',
        show_tile_names: bool = False
    ):
        """Generate a graph showing neighborhood frequency (overall, or stacked per tile)."""
        print(f"\nGenerating neighborhood frequency graph...")

        frequency_df = self.calculate_neighborhood_frequency(adata, cn_key, group_by_tile)

        n_cns = len(adata.obs[cn_key].cat.categories)
        if n_cns <= 20:
            colors_palette = sns.color_palette(color_palette, n_cns)
        else:
            colors_palette = sns.color_palette('husl', n_cns)

        if group_by_tile:
            fig, ax = plt.subplots(figsize=figsize)

            sorted_labels, colors_sorted = _sort_cn_labels_and_colors(frequency_df.columns, color_palette)
            sorted_cols = [c for c in sorted_labels if c in frequency_df.columns]
            frequency_df_sorted = frequency_df[sorted_cols]

            frequency_df_sorted.plot(kind='bar', stacked=True, ax=ax,
                                     color=colors_sorted, width=0.8)

            ax.set_xlabel('Tile', fontsize=12, fontweight='bold')
            ax.set_ylabel('Frequency (Proportion)', fontsize=12, fontweight='bold')
            ax.set_title('Cellular Neighborhood Frequency by Tile',
                        fontsize=14, fontweight='bold', pad=15)
            ax.legend(title='Cellular Neighborhood', bbox_to_anchor=(1.05, 1),
                     loc='upper left', fontsize=9)
            if show_tile_names:
                ax.set_xticklabels(ax.get_xticklabels(), rotation=45, ha='right')
            else:
                ax.set_xticklabels([])
            ax.grid(axis='y', alpha=0.3, linestyle='--')

            plt.tight_layout()
        else:
            plt.close('all')
