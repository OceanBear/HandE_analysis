"""
Group-based Cellular Neighborhood Analysis and Visualization

This script reads the original source h5ad tiles plus lightweight CN-label JSONs written by cn_unified_kmeans.py and generates:
1. Unified analysis visualizations (unified_analysis folder):
   - Unified CN composition heatmap
   - Overall and per-tile neighborhood frequency graphs
2. Group-specific analysis (<tile_size>mm_groups folder):
   - Group-based CN composition comparisons (vs overall)
   - Group-specific frequency visualizations
   - Combined per-tile frequency figure, grouped by category

Note: Individual per-tile spatial CN maps are generated by the separate
print_cn_tiles.py script, since that step re-renders one figure per
tile (potentially hundreds) and is the slowest part of the pipeline — keeping
it separate lets you skip it on faster iteration cycles.

All processed h5ad tiles are loaded into memory once per run and reused across
every downstream step (unified analysis, each group's subset, and the combined
per-tile frequency figure), rather than re-reading tiles from disk repeatedly.
"""

